import {
  createObject,
  createPaintMaterialWithPalette as paint,
  toRGB,
  XYZ,
} from "~/3D";
import { length } from "~/alias";
import { doTimes, flat, interpolate, repeat } from "~/common";

const PORTRAIT_OFFSET = 81,
  PORTRAIT_HALF_HEIGHT = 0.15,
  PORTRAIT_SCALE = PORTRAIT_HALF_HEIGHT / 20,
  PORTRAIT_POSITION = [0, 0, 1.2] as XYZ,
  // generated by scripts/encodePortrait.ts
  PORTRAIT_DATA =
    "B[SWWbB[UdPkB[PkHeWb_ZSWGJHV+R4E+R+G@6T3R;R;T3{6R;{6r;9q>w6}+RGJ4EHV+R4X@q>w9qUd_aPk9qIk@qPk_ag_Pkg_edPkedWjGJUG_ZHVGJSWR;r;gRBgIk9qGJ0:@64XB[HVSWHVB[GJ@6R;HePkIkHeIkBg_aWbUdWjedfngRg__ZUGgR_ZR;gRUGGJR;UGRnWjPkg__Z_aSW_ZGJ@6C-T30:$1$#$#C-@6~#{6T3UdWbB[_a_ZWb$#@#C-0:$#@6@#~#T3C-@#T3"; // 282 chars
export const portrait = (progress: number) =>
  createObject(
    [PORTRAIT_POSITION],
    [
      0,
      doTimes(length(PORTRAIT_DATA) / 2, (index: number) => [
        (PORTRAIT_DATA.charCodeAt(index * 2) - PORTRAIT_OFFSET) *
        PORTRAIT_SCALE,
        (PORTRAIT_DATA.charCodeAt(index * 2 + 1) - PORTRAIT_OFFSET) *
        PORTRAIT_SCALE,
        -2,
      ]),
    ],
    paint(
      ...flat(
        repeat(4, toRGB(270, interpolate([0, 20], progress), 8)),
        repeat(8, toRGB(220, interpolate([0, 60], progress), 93)),
        repeat(14, toRGB(265, interpolate([0, 18], progress), 63)),
        repeat(11, toRGB(270, interpolate([0, 12], progress), 45)),
        repeat(5, toRGB(217, interpolate([0, 27], progress), 65)),
        repeat(5, toRGB(217, interpolate([0, 18], progress), 43)),
      ),
    ),
  );
